hl.bind(mainMod .. " + ALT + k", hl.dsp.window.resize({ x = 0, y = -80, relative = true }))
hl.bind(mainMod .. " + ALT + j", hl.dsp.window.resize({ x = 0, y = 80, relative = true }))

-- Workspaces 1-9
