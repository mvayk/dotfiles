local mainMod = "SUPER"

local function sh(cmd)
    return hl.dsp.exec_cmd(cmd)
end

-- Apps
hl.bind(mainMod .. " + T", sh(terminal))
hl.bind(mainMod .. " + W", sh("firefox"))
hl.bind(mainMod .. " + D", sh("neovide"))
hl.bind(mainMod .. " + E", sh(fileManager))

-- Screenshots (saved to ~/Pictures/Screenshots and copied to clipboard)
local shotFile = [==["$HOME/Pictures/Screenshots/Screenshot from $(date '+%Y-%m-%d %H-%M-%S').png"]==]
local shotPrep = 'mkdir -p "$HOME/Pictures/Screenshots" && '

-- Region -> file + clipboard (niri: Mod+Shift+S, interactive screenshot)
hl.bind(mainMod .. " + SHIFT + S", sh(shotPrep .. [==[grim -g "$(slurp)" - | tee ]==] .. shotFile .. " | wl-copy"))
-- Whole screen (niri: Ctrl+Print)
hl.bind("CTRL + Print", sh(shotPrep .. "grim - | tee " .. shotFile .. " | wl-copy"))
-- Active window (niri: Alt+Print)
hl.bind(
    "ALT + Print",
    sh(
        shotPrep
            .. [==[grim -g "$(hyprctl activewindow -j | jq -r '"\(.at[0]),\(.at[1]) \(.size[0])x\(.size[1])"')" - | tee ]==]
            .. shotFile
            .. " | wl-copy"
    )
)
-- Region -> synced screenshots folder + clipboard (niri: End)
hl.bind(
    "End",
    sh(
        [==[grim -g "$(slurp)" - | tee ~/Documents/sync/pictures/screenshots/$(date +%Y-%m-%d_%H-%M-%S).png | wl-copy]==]
    )
)

-- Window management
hl.bind(mainMod .. " + Q", hl.dsp.window.close())
hl.bind(mainMod .. " + F", hl.dsp.window.fullscreen({ mode = "maximized", action = "toggle" })) -- maximize
hl.bind(mainMod .. " + SHIFT + F", hl.dsp.window.fullscreen({ action = "toggle" }))
hl.bind(mainMod .. " + V", hl.dsp.window.float({ action = "toggle" }))
hl.bind(mainMod .. " + R", hl.dsp.layout("togglesplit")) -- flip split direction (dwindle)
hl.bind(mainMod .. " + P", hl.dsp.window.pseudo())

hl.bind(
    mainMod .. " + M",
    sh("command -v hyprshutdown >/dev/null 2>&1 && hyprshutdown || hyprctl dispatch 'hl.dsp.exit()'")
)

-- Focus (hjkl)
